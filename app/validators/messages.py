def _fmt(value: Any) -> str:
    if isinstance(value, (list, tuple)):
        return ", ".join(_fmt(v) for v in value) or "—"
    return str(value)


def render(finding: dict[str, Any], lang: str = "en") -> str:
    table = MESSAGES.get(lang, MESSAGES["en"])
    template = table.get(finding["code"]) or MESSAGES["en"].get(finding["code"], finding["code"])
    params = {k: _fmt(v) for k, v in (finding.get("params") or {}).items()}
    try:
        return template.format(**params)
    except (KeyError, IndexError):
        return template


def render_all(findings: list[dict[str, Any]], lang: str = "en") -> list[dict[str, Any]]:
    return [{**f, "message": render(f, lang)} for f in findings]

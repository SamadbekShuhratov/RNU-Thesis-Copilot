"""Employee 1 reports: compliance summary, authorship log and the bi-weekly
progress e-mail. Everything here is computed from the real event log and
state — nothing is generated by the LLM, so progress cannot be fabricated."""
from __future__ import annotations

import datetime as dt
import difflib
import time
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, select_autoescape

from ..validators import blocking, render, validate_stage
from ..validators.text import flatten_text, word_count

TEMPLATES = Path(__file__).with_name("templates")
_env = Environment(loader=FileSystemLoader(str(TEMPLATES)), autoescape=select_autoescape([]),
                   trim_blocks=True, lstrip_blocks=True)


def authorship(state: dict) -> dict[str, dict[str, Any]]:
    """How much of each stage the student changed relative to the AI draft."""
    from ..orchestrator.state import stage_key

    out = {}
    for stage, draft in (state.get("ai_drafts") or {}).items():
        try:
            current = state.get(stage_key(stage))
        except KeyError:
            continue
        a, b = flatten_text(draft).split(), flatten_text(current).split()
        if not a and not b:
            continue
        ratio = difflib.SequenceMatcher(None, a, b, autojunk=False).ratio() if a and b else 0.0
        out[stage] = {"ai_words": len(a), "final_words": len(b), "changed_pct": round((1 - ratio) * 100, 1)}
    return out


def compliance_summary(state: dict) -> dict[str, Any]:
    per_stage = {}
    for stage in state.get("stages", []):
        if stage == "final":
            continue
        f = validate_stage(stage, state)
        per_stage[stage] = {"blocking": len(blocking(f)), "warnings": len(f) - len(blocking(f)),
                            "status": state.get("stage_status", {}).get(stage, "pending")}
    total_words = sum(word_count(flatten_text(state.get(k))) for k in
                      ("chapter1", "literature", "theory", "practical", "conclusion"))
    refs = state.get("references", [])
    return {
        "per_stage": per_stage,
        "total_words": total_words,
        "references_total": len(refs),
        "references_verified": len([r for r in refs if r.get("status") == "verified"]),
        "authorship": authorship(state),
        "generated_at": time.time(),
    }


def progress_report(state: dict, events: list[dict], days: int = 14, lang: str = "en",
                    now: float | None = None) -> dict[str, str]:
    now = now or time.time()
    since = now - days * 86400
    recent = [e for e in events if e["ts"] >= since]
    approved = [e for e in recent if e["kind"] == "approved"]
    drafts = [e for e in recent if e["kind"] == "stage_draft"]
    edits = [e for e in recent if e["kind"] == "edit"]
    revisions = [e for e in recent if e["kind"] == "revise"]
    refs_events = [e for e in recent if e["kind"] == "refs"]
    exp_events = [e for e in recent if e["kind"] == "experiments"]
    stage = state.get("stage")
    open_findings = []
    if stage and stage not in ("done",):
        try:
            open_findings = [render(f, lang) for f in blocking(validate_stage(stage, state))]
        except KeyError:
            open_findings = []
    p = state.get("project", {})
    o = state.get("outline") or {}
    refs = state.get("references", [])
    ctx = {
        "project": p,
        "title": o.get("selected_title") or p.get("name"),
        "start": dt.datetime.fromtimestamp(since).strftime("%d.%m.%Y"),
        "end": dt.datetime.fromtimestamp(now).strftime("%d.%m.%Y"),
        "approved": sorted({e["stage"] for e in approved if e.get("stage")}),
        "drafts": sorted({e["stage"] for e in drafts if e.get("stage")}),
        "n_edits": len(edits),
        "n_revisions": len(revisions),
        "n_refs_events": len(refs_events),
        "refs_verified": len([r for r in refs if r.get("status") == "verified"]),
        "refs_total": len(refs),
        "experiments_uploaded": bool(exp_events),
        "status": state.get("stage_status", {}),
        "current_stage": stage,
        "open_findings": open_findings,
        "authorship": authorship(state),
        "nails": o.get("nails", []),
        "goal": o.get("goal", ""),
    }
    name = f"progress_email_{lang}.j2"
    if not (TEMPLATES / name).exists():
        name = "progress_email_en.j2"
    text = _env.get_template(name).render(**ctx)
    subject, _, body = text.partition("\n")
    return {"subject": subject.replace("Subject:", "").strip(), "body": body.strip(),
            "to": p.get("supervisor_email", ""), "period_days": str(days)}

"""Real bibliographic sources — the only place references may come from.

* OpenAlex       — discovery (search) + abstracts
* Crossref       — independent DOI verification (title must match)
* Semantic Scholar — fallback discovery
* BibTeX import  — the student's own library (Zotero / Mendeley export)

Nothing in this module is generated by an LLM, so no reference can be
hallucinated; every entry carries the API it came from and a verification
status.
"""
from __future__ import annotations

import difflib
import re
import time
import unicodedata
from typing import Any

import requests

USER_AGENT = "RNU-Thesis-Copilot/1.0 (local academic assistant)"
TIMEOUT = 20


class SourceError(RuntimeError):
    pass


def _session() -> requests.Session:
    s = requests.Session()
    s.headers["User-Agent"] = USER_AGENT
    return s


SESSION = _session()


def normalize_doi(doi: str | None) -> str:
    if not doi:
        return ""
    doi = doi.strip()
    doi = re.sub(r"^(https?://(dx\.)?doi\.org/|doi:\s*)", "", doi, flags=re.IGNORECASE)
    return doi.lower()


def _ascii(s: str) -> str:
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()


def title_similarity(a: str, b: str) -> float:
    norm = lambda s: re.sub(r"[^a-z0-9 ]", " ", _ascii(s or "").lower()).split()  # noqa: E731
    return difflib.SequenceMatcher(None, " ".join(norm(a)), " ".join(norm(b))).ratio()


def make_key(ref: dict[str, Any], existing: set[str]) -> str:
    family = ""
    if ref.get("authors"):
        family = ref["authors"][0].get("family") or ref["authors"][0].get("given") or ""
    if not family:
        family = (ref.get("title") or "anon").split()[0]
    base = re.sub(r"[^a-z]", "", _ascii(family).lower()) or "ref"
    base = f"{base}{ref.get('year') or 'nd'}"
    key, i = base, 0
    while key in existing:
        key = base + "abcdefghijklmnopqrstuvwxyz"[i % 26] + ("" if i < 26 else str(i // 26))
        i += 1
    return key


def _split_name(display: str) -> dict[str, str]:
    parts = (display or "").strip().split()
    if not parts:
        return {"given": "", "family": ""}
    if len(parts) == 1:
        return {"given": "", "family": parts[0]}
    return {"given": " ".join(parts[:-1]), "family": parts[-1]}


def _openalex_abstract(inv: dict[str, list[int]] | None) -> str:
    if not inv:
        return ""
    positions = [(pos, word) for word, idxs in inv.items() for pos in idxs]
    return " ".join(w for _, w in sorted(positions))[:2500]


def from_openalex(work: dict[str, Any]) -> dict[str, Any]:
    source = ((work.get("primary_location") or {}).get("source") or {})
    biblio = work.get("biblio") or {}
    return {
        "title": (work.get("title") or work.get("display_name") or "").strip(),
        "authors": [_split_name(a.get("author", {}).get("display_name", ""))
                    for a in (work.get("authorships") or [])[:20]],
        "year": work.get("publication_year"),
        "venue": source.get("display_name") or "",
        "volume": biblio.get("volume") or "",
        "issue": biblio.get("issue") or "",
        "pages": "-".join(p for p in (biblio.get("first_page"), biblio.get("last_page")) if p) or "",
        "doi": normalize_doi(work.get("doi")),
        "url": (work.get("primary_location") or {}).get("landing_page_url") or work.get("id") or "",
        "abstract": _openalex_abstract(work.get("abstract_inverted_index")),
        "type": work.get("type") or "article",
        "cited_by_count": work.get("cited_by_count") or 0,
        "source": "openalex",
        "source_id": work.get("id", ""),
    }


def search_openalex(query: str, per_page: int = 8, from_year: int | None = None,
                    mailto: str = "") -> list[dict[str, Any]]:
    params: dict[str, Any] = {"search": query, "per-page": max(1, min(per_page, 50)),
                              "sort": "relevance_score:desc"}
    filters = ["has_doi:true"]
    if from_year:
        filters.append(f"from_publication_date:{int(from_year)}-01-01")
    params["filter"] = ",".join(filters)
    if mailto:
        params["mailto"] = mailto
    try:
        r = SESSION.get("https://api.openalex.org/works", params=params, timeout=TIMEOUT)
        r.raise_for_status()
    except requests.RequestException as exc:
        raise SourceError(f"OpenAlex search failed: {exc}") from exc
    return [from_openalex(w) for w in r.json().get("results", [])]


def search_semantic_scholar(query: str, limit: int = 8) -> list[dict[str, Any]]:
    params = {"query": query, "limit": max(1, min(limit, 50)),
              "fields": "title,year,authors,venue,externalIds,abstract,url,citationCount"}
    try:
        r = SESSION.get("https://api.semanticscholar.org/graph/v1/paper/search", params=params, timeout=TIMEOUT)
        r.raise_for_status()
    except requests.RequestException as exc:
        raise SourceError(f"Semantic Scholar search failed: {exc}") from exc
    out = []
    for p in r.json().get("data", []) or []:
        out.append({
            "title": p.get("title") or "",
            "authors": [_split_name(a.get("name", "")) for a in (p.get("authors") or [])[:20]],
            "year": p.get("year"),
            "venue": p.get("venue") or "",
            "volume": "", "issue": "", "pages": "",
            "doi": normalize_doi((p.get("externalIds") or {}).get("DOI")),
            "url": p.get("url") or "",
            "abstract": (p.get("abstract") or "")[:2500],
            "type": "article",
            "cited_by_count": p.get("citationCount") or 0,
            "source": "semantic_scholar",
            "source_id": p.get("paperId", ""),
        })
    return out


def from_crossref(msg: dict[str, Any]) -> dict[str, Any]:
    year = None
    for k in ("published-print", "published-online", "issued", "created"):
        parts = (msg.get(k) or {}).get("date-parts") or []
        if parts and parts[0] and parts[0][0]:
            year = parts[0][0]
            break
    return {
        "title": " ".join(msg.get("title") or []).strip(),
        "authors": [{"given": a.get("given", ""), "family": a.get("family", a.get("name", ""))}
                    for a in (msg.get("author") or [])[:20]],
        "year": year,
        "venue": " ".join(msg.get("container-title") or []),
        "volume": msg.get("volume", ""),
        "issue": msg.get("issue", ""),
        "pages": msg.get("page", ""),
        "doi": normalize_doi(msg.get("DOI")),
        "url": msg.get("URL", ""),
        "abstract": re.sub(r"<[^>]+>", "", msg.get("abstract", ""))[:2500],
        "type": msg.get("type", "article"),
        "cited_by_count": msg.get("is-referenced-by-count", 0),
        "source": "crossref",
        "source_id": msg.get("DOI", ""),
    }


def crossref_by_doi(doi: str) -> dict[str, Any] | None:
    doi = normalize_doi(doi)
    if not doi:
        return None
    try:
        r = SESSION.get(f"https://api.crossref.org/works/{requests.utils.quote(doi)}", timeout=TIMEOUT)
    except requests.RequestException as exc:
        raise SourceError(f"Crossref lookup failed: {exc}") from exc
    if r.status_code == 404:
        return None
    try:
        r.raise_for_status()
    except requests.RequestException as exc:
        raise SourceError(f"Crossref lookup failed: {exc}") from exc
    return from_crossref(r.json().get("message", {}))


def crossref_search(title: str, rows: int = 3) -> list[dict[str, Any]]:
    try:
        r = SESSION.get("https://api.crossref.org/works",
                        params={"query.bibliographic": title, "rows": rows}, timeout=TIMEOUT)
        r.raise_for_status()
    except requests.RequestException as exc:
        raise SourceError(f"Crossref search failed: {exc}") from exc
    return [from_crossref(m) for m in r.json().get("message", {}).get("items", [])]


def verify_reference(ref: dict[str, Any]) -> dict[str, Any]:
    """Verify against Crossref (independent of the discovery source).

    status: verified | mismatch | not_found | error
    """
    result = dict(ref)
    result["verified_at"] = time.time()
    try:
        if ref.get("doi"):
            found = crossref_by_doi(ref["doi"])
            if not found:
                result.update(status="not_found", verification={"method": "crossref_doi", "score": 0.0})
                return result
            score = title_similarity(ref.get("title", ""), found.get("title", ""))
            if score >= 0.85 or not ref.get("title"):
                for k in ("title", "authors", "year", "venue", "volume", "issue", "pages"):
                    if not result.get(k) and found.get(k):
                        result[k] = found[k]
                result.update(status="verified", verification={"method": "crossref_doi", "score": round(score, 3)})
            else:
                result.update(status="mismatch", verification={"method": "crossref_doi", "score": round(score, 3),
                                                               "crossref_title": found.get("title", "")})
            return result
        candidates = crossref_search(ref.get("title", ""))
        best, best_score = None, 0.0
        for c in candidates:
            s = title_similarity(ref.get("title", ""), c.get("title", ""))
            if s > best_score:
                best, best_score = c, s
        if best and best_score >= 0.92:
            result.update({k: result.get(k) or best.get(k) for k in ("authors", "year", "venue", "volume", "issue", "pages")})
            result["doi"] = best["doi"]
            result["url"] = result.get("url") or best.get("url", "")
            result.update(status="verified", verification={"method": "crossref_title", "score": round(best_score, 3)})
        else:
            result.update(status="not_found", verification={"method": "crossref_title", "score": round(best_score, 3)})
    except SourceError as exc:
        result.update(status="error", verification={"method": "crossref", "error": str(exc)})
    return result


# ── BibTeX ────────────────────────────────────────────────────────────────
_ENTRY_RE = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", re.MULTILINE)


def _bib_fields(body: str) -> dict[str, str]:
    fields: dict[str, str] = {}
    i = 0
    while i < len(body):
        m = re.compile(r"\s*(\w[\w-]*)\s*=\s*").match(body, i)
        if not m:
            i += 1
            continue
        name = m.group(1).lower()
        i = m.end()
        if i < len(body) and body[i] in "{\"":
            opener = body[i]
            closer = "}" if opener == "{" else "\""
            depth, j = 0, i
            while j < len(body):
                ch = body[j]
                if opener == "{" and ch == "{":
                    depth += 1
                elif ch == closer:
                    if opener == "{":
                        depth -= 1
                        if depth == 0:
                            break
                    elif j > i:
                        break
                j += 1
            value = body[i + 1:j]
            i = j + 1
        else:
            m2 = re.compile(r"([^,}\n]+)").match(body, i)
            value = m2.group(1) if m2 else ""
            i = m2.end() if m2 else i + 1
        fields[name] = re.sub(r"[{}]", "", re.sub(r"\s+", " ", value)).strip()
    return fields


def parse_bibtex(text: str) -> list[dict[str, Any]]:
    entries = []
    matches = list(_ENTRY_RE.finditer(text))
    for idx, m in enumerate(matches):
        etype, key = m.group(1).lower(), m.group(2)
        if etype in {"comment", "string", "preamble"}:
            continue
        end = matches[idx + 1].start() if idx + 1 < len(matches) else len(text)
        f = _bib_fields(text[m.end():end])
        authors = []
        for a in re.split(r"\s+and\s+", f.get("author", "")):
            a = a.strip()
            if not a:
                continue
            if "," in a:
                fam, _, giv = a.partition(",")
                authors.append({"given": giv.strip(), "family": fam.strip()})
            else:
                authors.append(_split_name(a))
        year = re.search(r"\d{4}", f.get("year", "") or f.get("date", ""))
        entries.append({
            "bibtex_key": key,
            "title": f.get("title", ""),
            "authors": authors,
            "year": int(year.group(0)) if year else None,
            "venue": f.get("journal") or f.get("booktitle") or f.get("publisher") or "",
            "volume": f.get("volume", ""), "issue": f.get("number", ""), "pages": f.get("pages", "").replace("--", "-"),
            "doi": normalize_doi(f.get("doi")),
            "url": f.get("url", ""),
            "abstract": f.get("abstract", "")[:2500],
            "type": etype,
            "cited_by_count": 0,
            "source": "bibtex",
            "source_id": key,
        })
    return entries
